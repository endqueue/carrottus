uint32_t cr_get_version(void) {
	/* Compiled into the library, so this is the library's version, not
	 * the version of the header the caller has. */
	return CARROTTUS_VERSION;
}

CR_RESULT cr_debug_name_set(void *object, const char *name) {
	if (!object)
		return CR_RESULT_NULL_OBJECT;
	if (CR_STALE(object, "cr_debug_name_set", "object"))
		return CR_RESULT_NULL_OBJECT;

	/* Every object that carries a debug name starts with a cr_object_head,
	 * which holds the name and the allocator it is copied and freed with. */
	return cr_object_name_set((cr_object_head *)object, name);
}

const char *cr_debug_name_get(void *object) {
	if (!object)
		return NULL;
	if (CR_STALE(object, "cr_debug_name_get", "object"))
		return NULL;
	return ((const cr_object_head *)object)->debug_name;
}

static void *cr_system_allocate(void *user_data, size_t size, size_t alignment) {
	(void)user_data;
	/* A size no rounding to the alignment can hold is refused here, on every
	 * platform, rather than left to the C library to notice. */
	if (size > SIZE_MAX - (alignment - 1))
		return NULL;
#if defined(_WIN32)
	return _aligned_malloc(size, alignment);
#else
	/* malloc already meets max_align_t's alignment. aligned_alloc may refuse
	 * a size that isn't a multiple of the alignment, so the size is rounded
	 * up to one. */
	if (alignment <= _Alignof(max_align_t))
		return malloc(size);
	return aligned_alloc(alignment, (size + alignment - 1) & ~(alignment - 1));
#endif
}

static void cr_system_free(void *user_data, void *memory, size_t size, size_t alignment) {
	(void)user_data;
	(void)size;
	(void)alignment;
#if defined(_WIN32)
	_aligned_free(memory);
#else
	free(memory);
#endif
}

CR_ALLOCATOR cr_allocator_system(void) {
	CR_ALLOCATOR allocator = {
	    .user_data = NULL,
	    .allocate  = cr_system_allocate,
	    .free      = cr_system_free,
	};
	return allocator;
}

